/// Map an NES palette index to opaque sRGB RGBA.
///
/// The input is masked to 6 bits, so raw palette-RAM bytes (already `$00-$3F`
/// after the PPU's write mask) and unmasked values both work. Display-only:
/// golden tests compare indexed buffers and never call this.
#[must_use]
pub fn indexed_to_rgba(index: u8) -> [u8; 4] {
    let [r, g, b] = NES_PALETTE_RGB[(index & 0x3F) as usize];
    [r, g, b, 0xFF]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_64_entries_map_to_opaque_rgba() {
        for i in 0..64u8 {
            let [_, _, _, a] = indexed_to_rgba(i);
            assert_eq!(a, 0xFF, "entry ${i:02X} must be opaque");
            let [r, g, b, _] = indexed_to_rgba(i);
            let [er, eg, eb] = NES_PALETTE_RGB[i as usize];
            assert_eq!((r, g, b), (er, eg, eb), "entry ${i:02X} mismatch");
        }
    }

    #[test]
    fn canonical_black_and_white_spot_checks() {
        // Canonical black is $0F; near-white rows are $20/$30.
        assert_eq!(indexed_to_rgba(0x0F), [0x00, 0x00, 0x00, 0xFF]);
        assert_eq!(indexed_to_rgba(0x30), [0xFC, 0xFC, 0xFC, 0xFF]);
        assert_eq!(indexed_to_rgba(0x00), [0x7C, 0x7C, 0x7C, 0xFF]);
        assert_eq!(indexed_to_rgba(0x20), [0xF8, 0xF8, 0xF8, 0xFF]);
    }

    #[test]
    fn input_is_masked_to_six_bits() {
        assert_eq!(indexed_to_rgba(0xFF), indexed_to_rgba(0x3F));
        assert_eq!(indexed_to_rgba(0x40), indexed_to_rgba(0x00));
    }
}
