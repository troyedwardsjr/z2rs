//! NES master-palette to RGBA mapping.
//!
//! The software PPU model itself works purely in *indexed* colour: every
//! pixel of [`crate::IndexedFrame`] is a 6-bit NES palette index (`$00-$3F`)
//! as stored in palette RAM, so golden tests compare indexed buffers without
//! any display transform in the loop. This module converts those indices to
//! sRGB RGBA **only** for on-screen display and for the magenta-mismatch
//! overlay written by [`crate::write_diff_ppm`].
//!
//! The table below is the widely circulated "common `.pal`" NTSC
//! approximation (FCEUX/Mesen-style decode of the 2C02 composite output).
//! Exact hues vary between PPU revisions, TVs and decoders, which is exactly
//! why verification never touches this table.

